import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ghb from "../data/cac-ghb.js";
import yhb from "../data/cac-yhb.js";

const CURRENT_YHB_COUNT = 152;
const LEGACY_YHB_FIRST_ID = 1002;
const currentEnglishNumbers = new Set(ghb.map(function (record) {
  return Number(record.metadata && record.metadata.number);
}));

const currentYhb = yhb
  .map(function (record, index) {
    return {
      record: record,
      index: index,
      sourceNumber: Number(record.metadata && record.metadata.number),
      isVarious: Boolean(record.metadata && record.metadata.isVarious)
    };
  })
  .filter(function (item) { return Number.isInteger(item.sourceNumber) && item.sourceNumber > 0; })
  .sort(function (a, b) {
    return a.sourceNumber - b.sourceNumber || Number(a.isVarious) - Number(b.isVarious) || a.index - b.index;
  })
  .map(function (item, sortedIndex) {
    return { ...item, sortedIndex: sortedIndex };
  })
  .filter(function (item) { return currentEnglishNumbers.has(item.sourceNumber); })
  .map(function (item) {
    const existingId = Number(item.record.metadata && item.record.metadata.hymnal_internal_id);
    return {
      ...item.record,
      metadata: {
        ...item.record.metadata,
        hymnal_internal_id: Number.isInteger(existingId) && existingId > 0
          ? existingId
          : LEGACY_YHB_FIRST_ID + item.sortedIndex
      }
    };
  });

if (currentYhb.length !== CURRENT_YHB_COUNT) {
  throw new Error("Expected " + CURRENT_YHB_COUNT + " Yorùbá records with current English printed numbers; found " + currentYhb.length + ".");
}

const outputPath = fileURLToPath(new URL("../data/cac-yhb-current.js", import.meta.url));
writeFileSync(
  outputPath,
  "// Generated by scripts/build-current-yhb.mjs; source archive: cac-yhb.js.\nexport default " +
    JSON.stringify(currentYhb, null, 2) +
    ";\n"
);
console.log("Wrote " + currentYhb.length + " current CAC YHB records to data/cac-yhb-current.js.");
